-- 4. age_gate_locked: the app's "am I locked?" check, right after sign-in.
-- Same name and answer type, so the app needs no change for it.
-- -----------------------------------------------------------------------------
create or replace function public.age_gate_locked()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  /*
    What it does: answers "is the signed-in caller's email on the refusal
      list?" (VC-30, now by email fingerprint, VC-75).
    Inputs: none; it uses auth.uid(), so people can only ask about themselves.
    Returns: true if their email is marked, otherwise false.
