-- =============================================================================
-- Migration: the age-gate refusal mark becomes an HMAC of the email only, and
-- age-locked (13-17) logins can be deleted (task VC-75, founder approval
-- 2026-10-28). Builds on VC-30 (20261026170000_age_gate_lock.sql) and VC-B13
-- (20261028120000_delete_account.sql).
--
-- Plain-language background:
-- * Before this, a 13-17 refusal kept the whole login (which holds the email)
--   for 12 months, with a mark pointing at the login id. The login couldn't
--   be deleted early, because deleting it would delete the mark too and the
--   person could simply try again.
-- * Now the mark is a fingerprint of the email instead: an HMAC (a keyed
--   hash). Same email in, same fingerprint out; but the fingerprint can't be
--   turned back into the email, and without the secret key nobody can even
--   test a guessed email against it. So the login (and the plain email) can
--   be deleted while the "don't let this email straight back in" protection
--   stays for its 12 months.
-- * "Normalised" email = trimmed and lowercased, so " Teen@X.com " and
--   "teen@x.com" give the same fingerprint. Nothing cleverer (no removing
--   dots or "+tags"): that would differ by email provider and could lock out
--   a different person.
--
-- Where the secret key lives: a Supabase Vault secret named
-- 'vc_age_refusal_hmac_key' (Vault stores it encrypted inside the database).
-- This migration creates it with 32 random bytes generated by the database
-- itself at the moment it runs, so the value is never in the repo, the app, a
-- log or this file. Each project (dev, later prod) gets its own key. Only
-- server functions owned by the database owner can read it. If the key were
-- ever lost, the marks would simply stop matching (nobody would be locked
-- out wrongly; the lock would just stop working until the marks expire).
--
-- What changes:
--   1. The key is created in Vault (if it isn't there yet).
--   2. private.age_gate_refusals: the user_id column is replaced by
--      email_hmac. Any existing marks are converted first (their login's
--      email is fingerprinted), so nobody already locked is unlocked.
--   3. complete_profile: "refused before?" now compares the caller's email
--      fingerprint with the marks, so it also catches a NEW login made with
--      the same email after the old one was deleted. A 13-17 answer stores a
--      fingerprint mark.
--   4. age_gate_locked (the app's "am I locked?" check at sign-in): the same
--      fingerprint comparison.
--   5. The 12-month cleanup: deletes expired marks, and first any login
--      without a profile whose email matches an expired mark (the locked
--      login it belonged to, if the person never deleted it).
--   6. delete_account: the VCLCK refusal is removed, so a locked login can
--      be deleted (the Blocked screen's "Delete my account"). The mark is not
--      linked to the login any more, so it stays.
--
-- Error codes (unchanged for the app): VCLCK "refused before" from
-- complete_profile. New: VCKEY if the Vault key is missing (a setup problem,
-- never expected in normal use).
-- =============================================================================

-- -----------------------------------------------------------------------------
-- 1. The secret key, in Vault. Generated here, never written down anywhere.
-- -----------------------------------------------------------------------------
do $$
begin
  -- Only create it once: running this on a project that already has a key
  -- must not replace it (that would make every existing mark stop matching).
  if not exists (select 1 from vault.secrets s where s.name = 'vc_age_refusal_hmac_key') then
    -- gen_random_bytes is pgcrypto's secure random generator; 32 bytes = 256
    -- bits, the usual key size for HMAC-SHA256. hex makes it plain text.
    perform vault.create_secret(
      encode(extensions.gen_random_bytes(32), 'hex'),
      'vc_age_refusal_hmac_key',
      'VC-75: key for the HMAC of the email in age-gate refusal marks. Never share or print.'
    );
  end if;
end;
$$;

-- -----------------------------------------------------------------------------
-- Helper: read the key.
-- -----------------------------------------------------------------------------
create function private.age_refusal_hmac_key()
returns text
language plpgsql
stable
security definer
set search_path = ''
as $$
/*
  What it does: returns the secret HMAC key from Vault.
  Inputs: none.
  Returns: the key as text. Raises VCKEY if it is missing, rather than
    silently fingerprinting with an empty key (which anyone could repeat).
  Why security definer: only the database owner may read Vault's decrypted
    view; app users never can (and can't call this function either).
*/
declare
  v_key text;
begin
  select d.decrypted_secret into v_key
  from vault.decrypted_secrets d
  where d.name = 'vc_age_refusal_hmac_key';
  if v_key is null or v_key = '' then
    -- No key value in the message, only the name of what is missing.
    raise exception 'The age-gate HMAC key is missing from Vault.' using errcode = 'VCKEY';
  end if;
  return v_key;
end;
$$;

comment on function private.age_refusal_hmac_key() is
  'VC-75: the Vault secret vc_age_refusal_hmac_key (raises VCKEY if missing). Server functions only.';

-- -----------------------------------------------------------------------------
-- Helper: the fingerprint itself, with the key passed in (pure maths).
-- -----------------------------------------------------------------------------
create function private.hmac_email(p_email text, p_key text)
returns text
language sql
immutable
security definer
set search_path = ''
as $$
  /*
    What it does: the email's fingerprint: HMAC-SHA256 of the trimmed,
      lowercased email, written as 64 hex characters.
    Inputs: p_email (may be null), p_key (the secret key).
    Returns: the 64-character fingerprint, or null when there is no email.
    Why a separate helper: the normalising rule (trim + lowercase) lives in
      ONE place, and the cleanup can read the key once and fingerprint many
      emails with it.
  */
  select case
    when p_email is null or btrim(p_email) = '' then null
    else encode(extensions.hmac(lower(btrim(p_email)), p_key, 'sha256'), 'hex')
  end;
$$;

comment on function private.hmac_email(text, text) is
  'VC-75: HMAC-SHA256 (hex) of lower(trim(email)) with the given key; null for no email.';

-- -----------------------------------------------------------------------------
-- Helper: fingerprint an email with the Vault key.
-- -----------------------------------------------------------------------------
create function private.age_refusal_email_hmac(p_email text)
returns text
language sql
stable
security definer
set search_path = ''
as $$
  /*
    What it does: the fingerprint used by the refusal marks.
    Inputs: p_email, an email address (may be null).
    Returns: the 64-character fingerprint, or null when there is no email.
  */
  select private.hmac_email(p_email, private.age_refusal_hmac_key());
$$;

comment on function private.age_refusal_email_hmac(text) is
  'VC-75: fingerprint of an email for the age-gate refusal marks (HMAC with the Vault key).';

-- Nobody in the app may run these; only the server functions below.
revoke execute on function private.age_refusal_hmac_key() from public, anon, authenticated;
revoke execute on function private.hmac_email(text, text) from public, anon, authenticated;
revoke execute on function private.age_refusal_email_hmac(text) from public, anon, authenticated;

-- -----------------------------------------------------------------------------
-- 2. The marks table: user_id -> email_hmac, converting existing marks first.
-- -----------------------------------------------------------------------------
alter table private.age_gate_refusals add column email_hmac text;

-- Fingerprint the email of each marked login (the login still exists: the
-- old mark was deleted with its login, so every mark has one).
update private.age_gate_refusals r
set email_hmac = private.age_refusal_email_hmac(u.email)
from auth.users u
where u.id = r.user_id;

do $$
begin
  -- A marked login with no email can't be converted. All logins here are
  -- email logins, so this should never happen; if it does, stop the
  -- migration (nothing is changed) rather than silently unlock someone.
  if exists (select 1 from private.age_gate_refusals r where r.email_hmac is null) then
    raise exception 'A refusal mark has no email to fingerprint; migration stopped.';
  end if;
end;
$$;

-- Dropping user_id also drops its primary key and the link to auth.users
-- (so deleting a login no longer deletes its mark: that is the point).
alter table private.age_gate_refusals drop column user_id;

-- One mark per email. The check makes it impossible to store anything but a
-- 64-character hex fingerprint here, so a plain email can never end up in it.
alter table private.age_gate_refusals
  add primary key (email_hmac),
  add constraint age_gate_refusals_email_hmac_shape check (email_hmac ~ '^[0-9a-f]{64}$');

comment on table private.age_gate_refusals is
  'VC-30/VC-75: emails refused by the 18+ gate (ages 13-17), as an HMAC fingerprint only, plus the time and a fixed reason. No email, id or birthdate. Deleted after 12 months.';
comment on column private.age_gate_refusals.email_hmac is
  'HMAC-SHA256 (hex) of the trimmed, lowercased email, keyed with the Vault secret vc_age_refusal_hmac_key.';

-- -----------------------------------------------------------------------------
-- Helper: is the CALLER's email marked?
-- -----------------------------------------------------------------------------
create function private.caller_age_refused()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  /*
    What it does: answers "is the signed-in caller's email on the refusal
      list?"
    Inputs: none; it uses auth.uid() to find the caller's own email.
    Returns: true or false (false when not signed in or no email).
    Why: complete_profile and age_gate_locked ask the same question; this
      keeps it in one place.
  */
  select exists (
    select 1
    from auth.users u
    join private.age_gate_refusals r
      on r.email_hmac = private.age_refusal_email_hmac(u.email)
    where u.id = auth.uid()
  );
$$;

comment on function private.caller_age_refused() is
  'VC-75: true when the caller''s email fingerprint matches an age-gate refusal mark.';

revoke execute on function private.caller_age_refused() from public, anon, authenticated;

-- -----------------------------------------------------------------------------
-- 3. complete_profile, version 3. Same inputs, same answers as version 2
-- (VC-30); only how a refusal is stored and found changes. `create or
-- replace` keeps its rights (signed-in users only).
-- -----------------------------------------------------------------------------
create or replace function public.complete_profile(p_display_name text, p_birthdate date)
returns text
language plpgsql
volatile
security definer
set search_path = ''
as $$
/*
  What it does: takes the signed-in person's name and date of birth and
  either creates their profile (18+) or refuses and records the refusal.
  Inputs:
    p_display_name - the name other people will see (1 to 40 characters after
                     trimming spaces).
    p_birthdate    - their date of birth. Since VC-74 the app asks for it
                     BEFORE the email, and sends it here only for 18+ dates;
                     this check stays the one that counts.
  Returns: 'created', 'refused_locked' (13-17) or 'refused_deleted' (under
  13), or raises VCLCK / VCDUP / VCDOB / VCNAM / 42501 (see the VC-30
  migration for each).
  Privacy rule: no message raised here contains the birthdate or the email.
*/
declare
  v_user_id uuid := auth.uid();
  v_name text := btrim(p_display_name);
  v_today date := private.age_gate_today();
  -- The caller's email fingerprint (null if the login has no email).
  v_hmac text;
begin
  -- 1. Must be signed in.
  if v_user_id is null then
    raise exception 'You need to sign in first.' using errcode = '42501';
  end if;

  -- 2. One answer at a time per login (see VC-30).
  perform pg_advisory_xact_lock(hashtext('vc_age_gate'), hashtext(v_user_id::text));

  -- 3. The login must still exist (a deleted login's token can live an
  --    hour). Its email is fingerprinted at once; the plain email is never
  --    stored anywhere by this function.
  select private.age_refusal_email_hmac(u.email) into v_hmac
  from auth.users u where u.id = v_user_id;
  if not found then
    raise exception 'Please sign in again.' using errcode = '42501';
  end if;

  -- 4. Refused before? This compares the EMAIL's fingerprint, so it also
  --    catches a new login made with the same email after the old one was
  --    deleted (VC-75). Same wording as before.
  if v_hmac is not null
     and exists (select 1 from private.age_gate_refusals r where r.email_hmac = v_hmac) then
    raise exception 'VibeCheck is for people 18 and older.' using errcode = 'VCLCK';
  end if;

  -- 5. One profile per login, so the birthdate can't be changed later.
  if exists (select 1 from public.profiles p where p.id = v_user_id) then
    raise exception 'Your profile is already set up.' using errcode = 'VCDUP';
  end if;

  -- 6. The birthdate must be a real past date (fixed message, no date in it).
  if p_birthdate is null or p_birthdate > v_today or p_birthdate < date '1900-01-01' then
    raise exception 'Please enter a valid date of birth.' using errcode = 'VCDOB';
  end if;

  -- 7a. Under 13: delete the login at once and keep nothing (VC-30).
  if not private.is_at_least_age(p_birthdate, v_today, 13) then
    delete from auth.users u where u.id = v_user_id;
    return 'refused_deleted';
  end if;

  -- 7b. 13 to 17: keep the login (so the person can still see the "sorry"
  --     screen and ask to be deleted) and store the fingerprint mark.
  --     Returning normally (not raising) keeps the mark saved.
  if not private.is_at_least_18(p_birthdate, v_today) then
    if v_hmac is null then
      -- No email to fingerprint (not possible with email sign-in): nothing
      -- could hold the lock, so keep nothing at all, as for under 13.
      delete from auth.users u where u.id = v_user_id;
      return 'refused_deleted';
    end if;
    -- "on conflict do nothing": a mark for this email already exists only
    -- if step 4 missed it in a race, and then the older mark stands.
    insert into private.age_gate_refusals (email_hmac) values (v_hmac)
    on conflict (email_hmac) do nothing;
    return 'refused_locked';
  end if;

  -- 8. Adults only from here. The name must be 1 to 40 characters.
  if v_name is null or char_length(v_name) not between 1 and 40 then
    raise exception 'Please enter a name of 1 to 40 characters.' using errcode = 'VCNAM';
  end if;

  -- 9. Create the profile. role and is_tester take their safe defaults.
  insert into public.profiles (id, display_name, birthdate)
  values (v_user_id, v_name, p_birthdate);
  return 'created';
end;
$$;

comment on function public.complete_profile(text, date) is
  'VC-B03/VC-30/VC-75: creates the caller''s profile if 18+ (New York date). Returns created | refused_locked (13-17, email fingerprint marked) | refused_deleted (under 13, login deleted). Errors: VCLCK email refused before, VCDUP done, VCDOB bad date, VCNAM bad name, 42501 not signed in.';

